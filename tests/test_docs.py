# ------------------------------------------------------------------------------------------ privacy

LEAKS = [
    ("an absolute home path", re.compile(r"/home/|/Users/|C:\\Users")),
    # Homelab host names are joined from fragments so this public file does not itself contain them.
    ("a maintainer or machine name", re.compile(
        r"\b(mpha|michael|mphinance|" + "|".join(a + b for a, b in (
            ("jup", "iter"), ("sat", "urn"), ("ve", "nus"), ("pi", "hole"), ("re", "bull"))) + r")\b", re.I)),
    ("an IP address", re.compile(r"\b\d{1,3}(?:\.\d{1,3}){3}\b")),
    ("an ssh alias or user@host", re.compile(r"\bssh\s+\S|\b[\w.-]+@[\w-]+\.[\w.-]+")),
]

# Exact, justified exceptions. Each is (file name, regex the offending line must match).
LEAK_EXCEPTIONS = [
    # The Kraken documentation URL really has /home/ in its path.
    ("*", re.compile(r"docs\.kraken\.com/home/")),
    # The publish checklist prints the grep that looks for this exact leak, and says what hits are fine.
    ("PUBLISH_CHECKLIST.md", re.compile(r"git grep .*/home/")),
    # The install command prints this repository's own public address (the maintainer asked for it); exact URL only.
    ("*", re.compile(r"github\.com/mphinance/trading-agent(\.git@portable-agent)?")),
    # The broker catalog the wizard's broker list is generated from (the maintainer asked for this link); exact URL only.
    ("*", re.compile(r"https://github\.com/mphinance/awesome-broker-mcp")),
    # Public GitHub org of the sources THIRD_PARTY.md credits (an address, not a private detail).
    ("THIRD_PARTY.md", re.compile(r"https://github\.com/mphinance/")),
    # The decision-tag legend in the style guide (docs/STYLE.md) names the tag [MICHAEL] by design.
    ("STYLE.md", re.compile(r"\[MICHAEL\]")),
    # Loopback is a documented default (the helper, local model ports), not a private address.
    ("*", re.compile(r"\b127\.0\.0\.1\b")),
]


def allowed(name: str, line: str, what: str) -> bool:
    if what == "an IP address":
        stripped = re.sub(r"\b127\.0\.0\.1\b", "", line)
        if not re.search(LEAKS[2][1], stripped):
            return True
    return any(fn in ("*", name) and rx.search(line) for fn, rx in LEAK_EXCEPTIONS)


@pytest.mark.parametrize("path", MD + generated_files(), ids=IDS + [p.name for p in generated_files()])
def test_no_private_paths_names_or_addresses(path):
    bad = []
    for n, line in enumerate(path.read_text(encoding="utf-8").split("\n"), 1):
        for what, rx in LEAKS:
            if rx.search(line) and not allowed(path.name, line, what):
                bad.append(f"{path.name}:{n} {what}: {line.strip()[:80]}")
    assert not bad, "\n".join(bad)


