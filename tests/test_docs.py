def test_svgs_are_self_contained_accessible_and_escaped(fresh):
    _, files = fresh
    svgs = {p: t for p, t in files.items() if p.suffix == ".svg"}
    assert len(svgs) == 4
    for path, text in svgs.items():
        root = ET.fromstring(text)                                  # well-formed, so escaped
        ns = {"s": "http://www.w3.org/2000/svg"}
        assert root.get("width", "").isdigit() and root.get("height", "").isdigit(), path.name
        assert (root.findtext("s:title", namespaces=ns) or "").strip(), path.name
        assert (root.findtext("s:desc", namespaces=ns) or "").strip(), path.name
        assert root.get("role") == "img"
        low = text.lower()
        assert 'xmlns="http://www.w3.org/2000/svg"' in text
        for elem in root.iter():
            tag = elem.tag.rsplit("}", 1)[-1]
            assert tag in {"svg", "title", "desc", "rect", "circle", "text", "g"}, f"{path.name}: <{tag}>"
            for k, v in elem.attrib.items():
                assert "http" not in v and "url(" not in v and "href" not in k, f"{path.name}: {k}={v}"
        for banned in ("@import", "font-face", "<style"):
            assert banned not in low, f"{path.name} contains {banned}"
        assert "monospace" in low
    done = svgs[ROOT / "docs" / "assets" / "wizard-done.svg"]
    assert "You are set up." in done and "&lt;home&gt;" in done


