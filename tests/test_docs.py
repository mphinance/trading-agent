def template_pages() -> list[Path]:
    return [p for p in MD if DOCS in p.parents and "spike" not in p.relative_to(DOCS).parts] + [ROOT / "README.md", ROOT / "THIRD_PARTY.md"]


@pytest.mark.parametrize("path", template_pages(), ids=[str(p.relative_to(ROOT)) for p in template_pages()])
def test_page_follows_the_template(path):
    lines = path.read_text(encoding="utf-8").split("\n")
    nonblank = [(i, ln) for i, ln in enumerate(lines) if ln.strip()]
    assert nonblank[0][1].startswith("# "), "first line must be the title"
    assert nonblank[1][1].strip() == "> [!NOTE]", f"second block must open with '> [!NOTE]', got {nonblank[1][1]!r}"
    k = 2
    while k < len(nonblank) and nonblank[k][1].startswith(">"):
        k += 1
    assert any("Status:" in ln for _, ln in nonblank[1:k]), "the callout must carry a Status: line"
    purpose = nonblank[k][1].strip()
    assert purpose.startswith("**") and purpose.count("**") >= 2, \
        f"a bold one-sentence purpose must follow the callout, got {purpose[:60]!r}"
    prose, _ = parse("\n".join(lines))
    h2 = [(n, ln) for n, ln in prose if ln.startswith("## ")]
    assert h2 and h2[-1][1].strip() == "## Related docs", "the last ## section must be Related docs"
    tail = [ln for n, ln in prose if n > h2[-1][0] and ln.strip()]
    assert tail and all(ln.startswith("- ") for ln in tail), "Related docs must be a bulleted list of links"
    assert all("](" in ln for ln in tail), "every Related docs bullet must link somewhere"


