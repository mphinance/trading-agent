def test_the_markdown_set_is_what_we_expect():
    names = set(IDS)
    assert {"README.md", "THIRD_PARTY.md", "docs/README.md", "docs/STYLE.md", "docs/SETUP.md"} <= names
    assert not any(n.startswith("tests/") for n in names)


@pytest.mark.parametrize("path", MD, ids=IDS)
def test_every_relative_link_and_anchor_resolves(path):
    bad = []
    for kind, target, _text, line in targets(path):
        if not target:
            bad.append(f"{path.name}:{line} empty {kind} target")
            continue
        if is_external(target):
            continue
        file_part, _, frag = target.partition("#")
        dest = path if not file_part else (path.parent / file_part).resolve()
        if not dest.exists():
            bad.append(f"{path.name}:{line} missing file {target}")
            continue
        if frag and dest.suffix == ".md" and frag.lower() not in anchors(dest):
            bad.append(f"{path.name}:{line} no heading for #{frag} in {dest.name}")
    assert not bad, "\n".join(bad)


def test_no_page_is_an_orphan():
    index = DOCS / "README.md"
    linked = set()
    for _kind, t, _x, _n in targets(index):
        if not is_external(t) and t.partition("#")[0]:
            linked.add((index.parent / t.partition("#")[0]).resolve())
    missing = [str(p.relative_to(ROOT)) for p in MD
               if DOCS in p.parents and p != index and p.resolve() not in linked]
    assert not missing, f"docs/README.md does not link: {missing}"
    root_links = {(ROOT / t.partition("#")[0]).resolve() for _k, t, _x, _n in targets(ROOT / "README.md")
                  if not is_external(t)}
    assert index.resolve() in root_links, "README.md must link docs/README.md"
    assert (ROOT / "THIRD_PARTY.md").resolve() in {(index.parent / t.partition("#")[0]).resolve()
                                                    for _k, t, _x, _n in targets(index) if not is_external(t)}


