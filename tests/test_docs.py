"""The docs are a product: links resolve, the style contract holds, and generated assets cannot drift.

Rules live in docs/STYLE.md. Transcripts and SVGs under docs/ are generated by scripts/render_transcript.py
from a real run against the shim hermes; the drift test regenerates them once per session and compares.
"""
from __future__ import annotations

import importlib.util
