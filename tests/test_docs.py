@pytest.fixture(scope="module")
def fresh():
    """One regeneration per session: {path: text}. Runs the real CLI against the shim in a temp home."""
    src = str(ROOT / "src")
    if src not in sys.path:
        sys.path.insert(0, src)
    spec = importlib.util.spec_from_file_location("render_transcript", RENDERER)
    mod = importlib.util.module_from_spec(spec)
    sys.modules["render_transcript"] = mod
    spec.loader.exec_module(mod)
    return mod, mod.render_all()


