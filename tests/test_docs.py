import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
RENDERER = ROOT / "scripts" / "render_transcript.py"

# Written as escapes so this file holds neither character itself.
EM, EN = "\u2014", "\u2013"

MERMAID_KEYWORDS = ("flowchart", "stateDiagram-v2", "sequenceDiagram")

# Markdown that is part of the project's documentation. Third-party fixtures under tests/ are not.
SKIP_DIRS = {".venv", ".git", ".superpowers", ".pytest_cache", "node_modules", "tests", "__pycache__", "src"}


def markdown_files() -> list[Path]:
    out = []
    for p in ROOT.rglob("*.md"):
        rel = p.relative_to(ROOT)
        if any(part in SKIP_DIRS for part in rel.parts[:-1]):
            continue
        out.append(p)
    return sorted(out)


def generated_files() -> list[Path]:
    return sorted((DOCS / "transcripts").glob("*.txt")) + sorted((DOCS / "assets").glob("*.svg"))


MD = markdown_files()
IDS = [str(p.relative_to(ROOT)) for p in MD]


# ------------------------------------------------------------------------------------------ parsing

def parse(text: str):
    """Split markdown into prose lines and fenced blocks.

    Returns (prose, fences). ``prose`` is [(line_number, line)] outside fences. ``fences`` is
    [(start_line, info_string, [content lines])]. A fence closes on a line of the same character with at
    least as many marks, so a four-backtick block can hold a three-backtick example.
    """
    prose, fences = [], []
    open_ch, open_n, info, start, body = "", 0, "", 0, []
    for n, line in enumerate(text.split("\n"), 1):
        m = re.match(r"^ {0,3}(`{3,}|~{3,})(.*)$", line)
        if open_n:
            if m and m.group(1)[0] == open_ch and len(m.group(1)) >= open_n and not m.group(2).strip():
                fences.append((start, info, body))
                open_n = 0
            else:
                body.append(line)
            continue
        if m:
            open_ch, open_n, info, start, body = m.group(1)[0], len(m.group(1)), m.group(2).strip(), n, []
            continue
        prose.append((n, line))
    if open_n:
        fences.append((start, info, body))
    return prose, fences


def strip_inline_code(line: str) -> str:
    return re.sub(r"`[^`]*`", "", line)


def slug(heading: str) -> str:
    h = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", heading)
    h = re.sub(r"[`*_~]", lambda m: "_" if m.group(0) == "_" else "", h).strip().lower()
    h = re.sub(r"[^\w\- ]", "", h)
    return h.replace(" ", "-")


def anchors(path: Path) -> set[str]:
    prose, _ = parse(path.read_text(encoding="utf-8"))
    seen: dict[str, int] = {}
    out = set()
    for _, line in prose:
        m = re.match(r"^#{1,6}\s+(.*?)\s*#*\s*$", line)
        if not m:
            continue
        s = slug(m.group(1))
        k = seen.get(s, 0)
        seen[s] = k + 1
        out.add(s if k == 0 else f"{s}-{k}")
    return out


MD_LINK = re.compile(r"(!?)\[([^\]]*)\]\(\s*<?([^)\s>]+)>?(?:\s+\"[^\"]*\")?\s*\)")
HTML_IMG = re.compile(r"<img\b[^>]*>", re.I)
HTML_ATTR = re.compile(r"""(\w+)\s*=\s*(?:"([^"]*)"|'([^']*)')""")
HTML_A = re.compile(r"<a\b[^>]*\bhref\s*=\s*\"([^\"]*)\"", re.I)


def targets(path: Path):
    """Every (kind, target, text, line) link or image in a page, outside code."""
    prose, _ = parse(path.read_text(encoding="utf-8"))
    out = []
    for n, line in prose:
        clean = strip_inline_code(line)
        for m in MD_LINK.finditer(clean):
            out.append(("image" if m.group(1) else "link", m.group(3), m.group(2), n))
        for m in HTML_IMG.finditer(clean):
            attrs = {k.lower(): (a or b) for k, a, b in HTML_ATTR.findall(m.group(0))}
            out.append(("image", attrs.get("src", ""), attrs.get("alt", ""), n))
        for m in HTML_A.finditer(clean):
            out.append(("link", m.group(1), "", n))
    return out


def is_external(t: str) -> bool:
    return bool(re.match(r"^[a-zA-Z][a-zA-Z0-9+.-]*:", t))


